CREATE TABLE Issue (
  `key`       BIGINT       NOT NULL AUTO_INCREMENT,
  id          VARCHAR(64)  NOT NULL,
  type        BIGINT       NOT NULL,
  name        VARCHAR(200) NOT NULL,
  description MEDIUMTEXT   NULL,          
  author      BIGINT       NOT NULL,
  assignee    BIGINT       NULL,
  status      BIGINT       NOT NULL,
  priority    BIGINT       NOT NULL,
  startDate   DATE         NOT NULL,
  dueDate     DATE         NULL,
  version     VARCHAR(64)  NOT NULL,    
  PRIMARY KEY (`key`),
  UNIQUE KEY uq_issue_id (id),
  KEY idx_issue_author   (author),
  KEY idx_issue_assignee (assignee),
  KEY idx_issue_status   (status),
  CONSTRAINT chk_issue_dates CHECK (dueDate IS NULL OR dueDate >= startDate),
  CONSTRAINT fk_issue_type     FOREIGN KEY (type)     REFERENCES IssueTypes (`key`),
  CONSTRAINT fk_issue_author   FOREIGN KEY (author)   REFERENCES Users (`key`),
  CONSTRAINT fk_issue_assignee FOREIGN KEY (assignee) REFERENCES Users (`key`) ON DELETE SET NULL,
  CONSTRAINT fk_issue_status   FOREIGN KEY (status)   REFERENCES Statuses (`key`),
  CONSTRAINT fk_issue_priority FOREIGN KEY (priority) REFERENCES Priorities (`key`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
